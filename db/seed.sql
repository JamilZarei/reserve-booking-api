-- ------------------------------------------------- daily price calendar
-- From 1405/08/10 (2026-11-01) to 1406/01/11 (2027-03-31)
--   Thursday and Friday nights: +25%      Yalda night (2026-12-21): +30%
--   Nowruz holidays (2027-03-19 to 03-31): +60%      rounded to 10,000 toman
INSERT INTO unit_price_calendar (unit_id, day, price, is_available)
SELECT u.id,
       d::date,
       round(u.base_price_per_night *
             CASE
               WHEN d::date BETWEEN '2027-03-19' AND '2027-03-31' THEN 1.60
               WHEN d::date = '2026-12-21'                       THEN 1.30
               WHEN extract(isodow FROM d) IN (4, 5)             THEN 1.25
               ELSE 1.00
             END / 10000) * 10000,
       TRUE
FROM unit u
CROSS JOIN generate_series('2026-11-01'::date, '2027-03-31'::date, interval '1 day') AS d;

-- Days the hosts have blocked
UPDATE unit_price_calendar SET is_available = FALSE
WHERE (unit_id = 1  AND day BETWEEN '2026-12-10' AND '2026-12-12')   -- villa repairs
   OR (unit_id = 21 AND day BETWEEN '2027-01-15' AND '2027-01-25')   -- Masuleh cabin closed for heavy snow
   OR (unit_id = 8  AND day BETWEEN '2027-03-25' AND '2027-03-31');  -- Abyaneh house: the host family's Nowruz stay

